"""Customer data files (`data/<id>.json`) and how to load them.

These files are the single source of every number in the app. They are made
up, generated by `scripts/generate_data.py`, and contain no real personal data.

A bank connected through the Plaid sandbox (`engine/plaid_adapter.py`) is
registered here under its own id and then loads like any file.
"""

from __future__ import annotations

from datetime import date
from functools import lru_cache
from pathlib import Path
from threading import Lock

from pydantic import BaseModel

from ..models import Account, Bill, Customer, Transaction

DATA_DIR = Path(__file__).resolve().parents[3] / "data"

# Transaction categories that move money between the customer's own accounts.
# They are never counted as spending.
TRANSFER_CATEGORIES = {"card_payment", "savings_transfer", "retirement_contribution", "transfer"}
INCOME_CATEGORIES = {"paycheck"}
RETIREMENT_CONTRIBUTION = "retirement_contribution"
LATE_FEE = "late_fee"
# Bills that are really debt payments or account events: modeled from accounts instead.
DEBT_BILL_CATEGORIES = {"auto_loan", "card_payment", "mortgage", "personal_loan", "cd_maturity"}


class CustomerData(BaseModel):
    customer: Customer
    accounts: list[Account]
    bills: list[Bill]
    transactions: list[Transaction]
    # Set for a connected bank only (empty for the made-up files): where the data came from, and every default
    # the adapter had to fill in, so "show the math" can list them.
    source: str | None = None
    assumptions: list[str] = []
    account_notes: dict[str, list[str]] = {}  # account id -> notes for that account's balance
    indicator_notes: dict[str, list[str]] = {}  # health indicator id -> notes for that indicator
    data_checks: list[str] = []  # where the bank's data doesn't fit the model's flows (also in assumptions)

    def account(self, account_id: str) -> Account:
        return next(a for a in self.accounts if a.id == account_id)


@lru_cache(maxsize=None)
def _load_file(customer_id: str) -> CustomerData:
    path = DATA_DIR / f"{customer_id}.json"
    return CustomerData.model_validate_json(path.read_text(encoding="utf-8"))


# Connected (Plaid sandbox) customers, in memory only.
_CONNECTED: dict[str, CustomerData] = {}
_CONNECTED_LOCK = Lock()


def load(customer_id: str) -> CustomerData:
    connected = _CONNECTED.get(customer_id)
    return connected if connected is not None else _load_file(customer_id)


def register(data: CustomerData) -> None:
    with _CONNECTED_LOCK:
        _CONNECTED[data.customer.id] = data


def unregister(customer_id: str) -> None:
    with _CONNECTED_LOCK:
        _CONNECTED.pop(customer_id, None)


def is_connected(customer_id: str) -> bool:
    return customer_id in _CONNECTED


# ---------------------------------------------------------------------------
# How much history a customer has (the made-up files have exactly 12 months)
# ---------------------------------------------------------------------------

def history_days(data: CustomerData, today: date) -> int:
    """Days from the first transaction through today (0 with no transactions)."""
    dates = [t.date for t in data.transactions if t.date <= today]
    return (today - min(dates)).days + 1 if dates else 0


def history_months(data: CustomerData, today: date) -> int:
    """Whole months of history, at most 12 (the window the engine learns from). 365 days -> 12."""
    return min(12, history_days(data, today) * 12 // 365)


MIN_FORECAST_MONTHS = 3  # averages and spreads need a few months of history
MIN_BACKTEST_MONTHS = 12  # the backtest learns from 9 months and hides the last 3


class NotEnoughHistory(ValueError):
    """Too little transaction history for this calculation; the message says so in plain words."""


def require_history(customer_id: str, today: date, months: int, what: str) -> None:
    data = load(customer_id)
    have = history_months(data, today)
    if have < months:
        days = history_days(data, today)
        raise NotEnoughHistory(
            f"Not enough history for {what}: the bank sent {days} day{'s' if days != 1 else ''} of transactions, "
            f"and {what} needs at least {months} months. The score and accounts still work.")
