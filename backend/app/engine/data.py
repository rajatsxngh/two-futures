"""Customer data files (`data/<id>.json`) and how to load them.

These files are the single source of every number in the app. They are made
up, generated by `scripts/generate_data.py`, and contain no real personal data.
"""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path

from pydantic import BaseModel

from ..models import Account, Bill, Customer, Transaction

DATA_DIR = Path(__file__).resolve().parents[3] / "data"

# Transaction categories that move money between the customer's own accounts.
# They are never counted as spending.
TRANSFER_CATEGORIES = {"card_payment", "savings_transfer", "retirement_contribution", "transfer"}
INCOME_CATEGORIES = {"paycheck"}
RETIREMENT_CONTRIBUTION = "retirement_contribution"
LATE_FEE = "late_fee"
# Bills that are really debt payments or account events: modeled from accounts instead.
DEBT_BILL_CATEGORIES = {"auto_loan", "card_payment", "mortgage", "personal_loan", "cd_maturity"}


class CustomerData(BaseModel):
    customer: Customer
    accounts: list[Account]
    bills: list[Bill]
    transactions: list[Transaction]

    def account(self, account_id: str) -> Account:
        return next(a for a in self.accounts if a.id == account_id)


@lru_cache(maxsize=None)
def load(customer_id: str) -> CustomerData:
    path = DATA_DIR / f"{customer_id}.json"
    return CustomerData.model_validate_json(path.read_text(encoding="utf-8"))
